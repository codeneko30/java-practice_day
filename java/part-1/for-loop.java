
// simple for loop

class forLoop{
    public static void main(String[] args){
        for(int i=0; i<10; i++){
            System.out.println(i);
        }
    }
}


// fore each loop

 class forEachLoop {
    public  static void main(String[] args) {
        String [] names = {"Karim", "Rahim", "Salam"};
        
        for (String name : names) {
            System.out.println( name);
        }
    }
}